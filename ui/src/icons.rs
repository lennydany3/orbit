#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_icon_is_a_group_of_strokes_on_the_24_grid_with_its_own_name() {
        let all = [&HOME, &WORKFLOW, &BELL, &NOTEBOOK, &MUSIC, &SETTINGS, &MINUS, &PLUS, &TRASH, &PENCIL, &PLAY, &LINK, &SEARCH, &CHECK, &CLOSE, &REFRESH, &VOLUME, &CHEVRON_DOWN, &EXTERNAL,
                   &KEYBOARD, &TYPE, &CLOCK, &TASKS, &FILE, &MIC, &MOUSE];
        let mut names: Vec<&str> = all.iter().map(|i| i.name).collect();
        names.sort_unstable();
        names.dedup();
        assert_eq!(names.len(), all.len(), "names are unique: the glyph atlas keys on them");
        for icon in all {
            assert_eq!(icon.view, 24.0);
            assert!(icon.body.starts_with("<g fill=\"none\"") && icon.body.ends_with("</g>") && icon.body.contains("currentColor"), "{}", icon.name);
        }
    }
}
